/**
 * Catalogue generation templates.
 *
 * The hand-written products in `products.ts` are the flagship listings; this
 * file supplies the vocabulary the generator uses to fill each category out to
 * a realistic depth (see `catalog.ts`).
 *
 * Everything here is invented for this project: brands, series names, copy and
 * specifications. No real manufacturer's trademarks or marketing text is used.
 *
 * A template describes one subcategory. Names are composed from
 * `{brand} {series} {variant} {type}` by default, so a handful of vocabulary
 * lists yields dozens of coherent, distinct products -- and because the
 * generator walks the combinations deterministically, the same template always
 * produces the same catalogue.
 */

export interface SubcategoryTemplate {
  category: string;
  subcategory: string;
  brands: string[];
  series: string[];
  /** Model qualifier: capacity, size, generation, finish. May be ''. */
  variants: string[];
  /** The noun a customer would search for. */
  types: string[];
  /** Rupees, inclusive. The generator picks deterministically within it. */
  price: [number, number];
  /** Overrides the default `{brand} {series} {variant} {type}`. */
  nameTemplate?: string;
  /** One is chosen per product; placeholders are filled like names. */
  descriptions: string[];
  /** Four are chosen per product. */
  features: string[];
  /** Label -> value pool; one value chosen per product. */
  specs: Array<[string, string[]]>;
}

